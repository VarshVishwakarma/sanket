export type TranslationKey = keyof typeof messages.en;

export function translate(language: Language, key: TranslationKey, variables: Record<string, string | number> = {}): string {
  return Object.entries(variables).reduce((text, [name, value]) => text.replaceAll(`{${name}}`, String(value)), messages[language][key]);
}

export function riskLabel(language: Language, risk: "critical" | "watch" | "stable"): string {
  return translate(language, risk === "critical" ? "statusCritical" : risk === "watch" ? "statusWatch" : "statusStable");
}

export function donorStatusLabel(language: Language, status: "recommended" | "review" | "not-eligible"): string {
  return translate(language, status === "recommended" ? "recommended" : status === "review" ? "review" : "notEligible");
}

export function scenarioLabel(language: Language, id: "baseline" | "surge" | "delay"): string {
  return translate(language, id);
}

export function scenarioDescription(language: Language, id: "baseline" | "surge" | "delay"): string {
  return translate(language, `${id}Description` as TranslationKey);
}

export function auditAction(language: Language, action: string): string {
  if (action === "Risk recalculated") return translate(language, "eventRisk");
  if (action === "Rehearsal opened") return translate(language, "eventRehearsal");
  if (action === "Stock updated") return translate(language, "eventStock");
  if (action === "Transfer approved") return translate(language, "eventApproval");
  return action;
}

export function auditDetail(language: Language, event: { action: string; detail: string }): string {
  if (event.action === "Transfer approved") {
    if (language === "hi") {
      const match = event.detail.match(/^(\d+)\s+(.+?)\s+moved into\s+(.+)$/);
      return match ? translate(language, "eventTransferDetail", { quantity: match[1], medicine: match[2], facility: match[3] }) : event.detail;
    }
    return event.detail;
  }
  if (language === "hi") {
    if (event.detail.includes("moved to critical")) return "नॉर्थ स्टार • वैनकोमाइसिन 500mg गंभीर जोखिम में पहुंची";
    if (event.detail.includes("Shortage response")) return "नॉर्थ स्टार मेडिकल सेंटर के लिए कमी प्रतिक्रिया";
    if (event.detail.includes("Stock updated")) return "रिवरबेंड • नॉर्मल सलाइन +300 आने वाला स्टॉक";
  }
  return event.detail;
}
